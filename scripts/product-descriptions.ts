async function main() {
  const apply = process.argv.includes("--apply");
  let changed = 0;
  for (const [slug, plan] of Object.entries(PLANS)) {
    const product = await db.product.findUnique({ where: { slug }, select: { id: true, name: true, description: true } });
    if (!product) throw new Error(`Товар ${slug} не найден`);
    const current = product.description ?? "";
    if (current === plan.text) {
      console.log(`${slug}: описание уже стоит — пропускаю.`);
      continue;
    }
    if (current !== plan.expect) {
      console.log(`${slug}: ПРОПУСК. В базе уже другой текст, скрипт его не трогает:\n  ${current.slice(0, 120)}`);
      continue;
    }
    const meta = plan.text.replace(/\n/g, " ").slice(0, 180);
    console.log(`\n=== ${product.name} ===\n${plan.text}\n--- в выдачу уйдёт ---\n${meta}…`);
    changed++;
    if (apply) await db.product.update({ where: { id: product.id }, data: { description: plan.text } });
  }
  console.log(apply ? `\nЗаписано товаров: ${changed}.` : `\nИзменится товаров: ${changed}. Это предварительный показ, для записи добавьте --apply`);
}

main()
  .catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
